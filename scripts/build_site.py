def render_template(tpl, locales, lang, extra):
    def sub(m):
        key, mode = m.group(1), m.group(2)
        if key in extra:
            return extra[key]
        val = tr(locales, lang, key)
        return html.escape(val, quote=True) if mode == "attr" else html.escape(val, quote=False)
    return re.sub(r"\{\{(\w+)(?:\|(\w+))?\}\}", sub, tpl)


