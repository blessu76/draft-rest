def asset_version(root):
    h = hashlib.sha1()
    for n in ("site.css", "site.js"):
        h.update((Path(root) / "assets" / n).read_bytes())
    h.update((Path(root) / LOCALTIME_JS).read_bytes())  # inlined into blog pages: a new module bumps ?v=
    return h.hexdigest()[:8]


def git_date(root, paths):
    """Date (YYYY-MM-DD, KST) of the last commit touching `paths`; today if they have uncommitted changes."""
    today = dt.datetime.now(KST).date().isoformat()
    try:
        st = subprocess.run(["git", "-C", str(root), "status", "--porcelain", "--"] + list(paths),
                            capture_output=True, text=True, timeout=20)
        if st.returncode != 0 or st.stdout.strip():
            return today
        lg = subprocess.run(["git", "-C", str(root), "log", "-1", "--format=%cd", "--date=format-local:%Y-%m-%d", "--"] + list(paths),
                            capture_output=True, text=True, timeout=20, env={"TZ": "Asia/Seoul", "PATH": "/usr/bin:/bin:/usr/local/bin:/opt/homebrew/bin"})
        d = lg.stdout.strip()
        return d if lg.returncode == 0 and re.match(r"^\d{4}-\d{2}-\d{2}$", d) else today
    except (OSError, subprocess.SubprocessError):
        return today


