def replace_between(text, start_marker, end_marker, new, where):
    s, e = text.find(start_marker), text.find(end_marker)
    if s == -1 or e == -1 or e < s:
        raise SystemExit("marker not found in %s: %s ... %s" % (where, start_marker, end_marker))
    s += len(start_marker)
    return text[:s] + "\n" + new + text[e:]


